/** Why a message cannot be signed yet, or null. `allowed` is the list of rooms the page carries. */
export function messageProblem(room, text, allowed) {
  if (!Array.isArray(allowed) || !allowed.includes(room)) return "Choose a room from the list.";
  if (RESERVED.includes(room)) return "This room is reserved for signed censuses.";
  const swept = sweep(text);
  if (swept === "") return "Write your message.";
  if (/\[[^\]]*\]/.test(swept)) return "Replace every part in [brackets] with your own words.";
  if ([...swept].length > MAX_TEXT) return `Keep it under ${MAX_TEXT} characters.`;
  return null;
}

/** Signs the exact Technocore payload and checks the signature before anything else sees it. */
export async function signMessage(subtle, identity, room, nonce, text) {
  const swept = sweep(text);
  const data = new TextEncoder().encode(`${room}|${nonce}|${swept}`);
  const sig = b64url(new Uint8Array(await subtle.sign({ name: "Ed25519" }, identity.privateKey, data)));
  const pub = await subtle.importKey("raw", publicKey(identity.did), { name: "Ed25519" }, false, ["verify"]);
  const back = unb64url(sig, 64);
  if (sig.length !== 86 || !back || !(await subtle.verify({ name: "Ed25519" }, pub, back, data))) {
    throw new WalletError("signature", "The message could not be signed correctly; nothing was sent.");
  }
  return { room, nonce, text: swept, did: identity.did, sig };
}

/** A nonce above any this key could have spent: the millisecond clock, at least 13 digits. */
export const nextNonce = (now = Date.now()) => String(Math.max(1, Math.floor(now)));

/** A dated proof of one publication attempt, with the complete server reply when there is one. */
export function proofOf(signed, outcome, reply, stored, at = new Date().toISOString()) {
  return {
    schema: PROOF_SCHEMA,
    outcome,
    recorded_at: at,
    room: signed.room,
    did: signed.did,
    nonce: signed.nonce,
    text: signed.text,
    sig: signed.sig,
    signed_payload: `${signed.room}|${signed.nonce}|${signed.text}`,
    seq: stored?.seq ?? null,
    ts: stored?.ts ?? null,
    server_reply: reply ?? null,
    note: "seq and ts are assigned by technocore.chat and are not covered by the signature.",
  };
}
